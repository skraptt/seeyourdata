// Interface translations: English, German (Deutsch) and Turkish (Türkçe).
//
// t('key', { vars }) returns the text in the current language, falling back
// to English. A message is either a string or a function of its variables
// (for plurals and word order). To add a language: copy the `en` block, give
// it a new code, translate it, and add the code to LANG_NAMES.

export const LANG_NAMES = { en: 'English', de: 'Deutsch', tr: 'Türkçe' };

let current = 'en';

export function setLang(lang) {
  current = MESSAGES[lang] ? lang : 'en';
  return current;
}

export function getLang() {
  return current;
}

/** Picks a supported language from a browser language tag like "de-AT". */
export function detectLang(tag) {
  const base = String(tag || '').toLowerCase().split(/[-_]/)[0];
  return MESSAGES[base] ? base : 'en';
}

export function t(key, vars = {}) {
  const m = MESSAGES[current][key] ?? MESSAGES.en[key];
  if (m == null) return key;
  return typeof m === 'function' ? m(vars) : m;
}

/** "A, B and C" in the current language. */
export function joinList(items) {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')}${t('and')}${items[items.length - 1]}`;
}

